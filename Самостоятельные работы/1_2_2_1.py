# Описание функции программы

# Импортируемые модули
import math

# Глобальная переменная
PI = 3.14159

# Основная функция программы
def main():
	radius = float(input("Введите радиус круга"))
	area = PI * radius ** 2
	print(f"Площадь круга равна {area:.2f}")

# Запускаем программу
if __name__ == "__main__":
	main()